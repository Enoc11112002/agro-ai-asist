export interface ProximitySearchResult {
  targetDate: string;
  exactMatch: boolean;
  deltaDays: number;
  closestScene: SentinelScene;
  nearbyScenes: SentinelScene[];
  searchQuality: 'Excelente (Pase Limpio)' | 'Bueno (<5 días)' | 'Aceptable';
}

/**
 * Intelligent temporal proximity search algorithm for Sentinel-2 SR Harmonized collection.
 * Prevents app crashing if a chosen date doesn't coincide with a satellite overpass,
 * automatically snapping to the nearest cloud-free pass with cloud cover < 25%.
 */
export function findNearestSentinelScene(targetDateStr: string): ProximitySearchResult {
  const targetTime = new Date(targetDateStr).getTime();
  
  if (isNaN(targetTime)) {
    // Default to latest scene
    const defaultScene = SENTINEL_SCENES[0];
    return {
      targetDate: defaultScene.date,
      exactMatch: true,
      deltaDays: 0,
      closestScene: defaultScene,
      nearbyScenes: SENTINEL_SCENES.slice(0, 4),
      searchQuality: 'Excelente (Pase Limpio)'
    };
  }

  let minDiff = Infinity;
  let closest = SENTINEL_SCENES[0];

  for (const scene of SENTINEL_SCENES) {
    const sceneTime = new Date(scene.date).getTime();
    const diffDays = Math.abs((sceneTime - targetTime) / (1000 * 60 * 60 * 24));
    if (diffDays < minDiff) {
      minDiff = diffDays;
      closest = scene;
    }
  }

  const exactMatch = minDiff < 0.5;
  const deltaDays = Math.round(minDiff);

  const quality =
    deltaDays <= 2
      ? 'Excelente (Pase Limpio)'
      : deltaDays <= 7
      ? 'Bueno (<5 días)'
      : 'Aceptable';

  // Sort nearby scenes by proximity
  const sorted = [...SENTINEL_SCENES].sort((a, b) => {
    const diffA = Math.abs(new Date(a.date).getTime() - targetTime);
    const diffB = Math.abs(new Date(b.date).getTime() - targetTime);
    return diffA - diffB;
  });

  return {
    targetDate: targetDateStr,
    exactMatch,
    deltaDays,
    closestScene: closest,
    nearbyScenes: sorted.slice(0, 5),
    searchQuality: quality
  };
}
